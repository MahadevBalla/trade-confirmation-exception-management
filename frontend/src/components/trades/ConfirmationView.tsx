import React, { useState } from 'react';
import type { ConfirmationRecord } from '../../types/tcem';
import { Copy, Check, Download, ShieldCheck, AlertCircle } from 'lucide-react';

interface ConfirmationViewProps {
  confirmation?: ConfirmationRecord;
}

export const ConfirmationView: React.FC<ConfirmationViewProps> = ({ confirmation }) => {
  const [copied, setCopied] = useState(false);

  if (!confirmation) {
    return (
      <div className="p-8 text-center border border-slate-800 rounded-xl bg-slate-950/40 text-slate-400">
        <AlertCircle size={24} className="mx-auto mb-2 text-slate-500" />
        <p className="text-sm">No confirmation generated for this trade yet.</p>
        <p className="text-xs text-slate-500 mt-1">Confirmation is generated only after passing STP validation rules.</p>
      </div>
    );
  }

  const handleCopy = () => {
    navigator.clipboard.writeText(confirmation.confirmationBody);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const element = document.createElement('a');
    const file = new Blob([confirmation.confirmationBody], { type: 'text/plain' });
    element.href = URL.createObjectURL(file);
    element.download = `${confirmation.confirmationId}-${confirmation.tradeId}.txt`;
    document.body.appendChild(element);
    element.click();
    document.body.removeChild(element);
  };

  return (
    <div className="space-y-4">
      {/* Header Info */}
      <div className="flex flex-wrap items-center justify-between gap-3 p-4 rounded-xl border border-slate-800 bg-slate-900/60">
        <div>
          <div className="flex items-center gap-2">
            <h4 className="text-sm font-semibold text-white">{confirmation.confirmationId}</h4>
            <span className="text-xs px-2 py-0.5 rounded-full bg-emerald-500/10 text-emerald-400 border border-emerald-500/20 font-medium">
              STATUS: {confirmation.status}
            </span>
            {confirmation.isDuplicateSuppressed && (
              <span className="text-xs px-2 py-0.5 rounded-full bg-cyan-500/10 text-cyan-400 border border-cyan-500/20 font-medium">
                DUPLICATE SUPPRESSED
              </span>
            )}
          </div>
          <p className="text-xs text-slate-400 mt-1">
            Template: <span className="font-mono text-slate-300">{confirmation.templateId} (v{confirmation.templateVersion})</span> • Generated by: <span className="text-slate-300">{confirmation.generatedBy}</span>
          </p>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={handleCopy}
            className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-medium border border-slate-700 transition-colors"
          >
            {copied ? <Check size={14} className="text-emerald-400" /> : <Copy size={14} />}
            <span>{copied ? 'Copied' : 'Copy Text'}</span>
          </button>
          <button
            onClick={handleDownload}
            className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-indigo-600 hover:bg-indigo-500 text-white text-xs font-medium transition-colors shadow-sm"
          >
            <Download size={14} />
            <span>Download Note</span>
          </button>
        </div>
      </div>

      {/* Confirmation Fingerprint Box (FR6 & Stretch Duplicate Suppression) */}
      <div className="p-3.5 rounded-xl border border-slate-800 bg-slate-950/70 text-xs space-y-1.5">
        <div className="flex items-center gap-2 text-slate-300 font-semibold">
          <ShieldCheck size={15} className="text-emerald-400" />
          <span>Confirmation SHA-256 Fingerprint (Confirmable Fields)</span>
        </div>
        <p className="font-mono text-[11px] text-emerald-400/90 break-all bg-slate-900/80 p-2 rounded border border-slate-800">
          {confirmation.confirmationFingerprint}
        </p>
        {confirmation.previousConfirmationFingerprint && (
          <p className="text-[11px] text-slate-400">
            Previous Fingerprint: <span className="font-mono text-slate-500 break-all">{confirmation.previousConfirmationFingerprint}</span>
          </p>
        )}
      </div>

      {/* Rendered Confirmation Document */}
      <div className="rounded-xl border border-slate-800 bg-slate-950 p-4 font-mono text-xs text-slate-200 leading-relaxed overflow-x-auto whitespace-pre-wrap max-h-96">
        {confirmation.confirmationBody}
      </div>
    </div>
  );
};
